export function buildComments(score: number, moodTag: string): AuraSummary {
  const mood = moodTag as MoodType;
  const moodData = MOOD_COMMENTS[mood];
  
  if (!moodData) {
    // fallback
    return {
      keywords: ["균형", "안정"],
      tone: "안정",
      oneLiner: "오늘의 기운을 분석 중입니다.",
      advice: "자신의 상태를 주의깊게 관찰하세요."
    };
  }

  // score에 따라 high/mid/low 선택
  let pool: AuraSummary[];
  if (score >= 60) {
    pool = moodData.high;
  } else if (score >= 35) {
    pool = moodData.mid;
  } else {
    pool = moodData.low;
  }

  // 랜덤하게 하나 선택 (시간 기반 시드로 매번 조금씩 다르게)
  const seed = Math.floor(Date.now() / (1000 * 60 * 30)); // 30분마다 변경
  const index = (seed + score) % pool.length;
  
  return pool[index];
}
