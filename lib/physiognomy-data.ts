// ============================================
// 메인 분석 함수
// ============================================
export function analyzeFaceDetailed(
  topBrightness: number,
  midBrightness: number,
  bottomBrightness: number
): DetailedFortune {
  // 각 영역 분석 (10단계 세분화)
  const foreheadData = FOREHEAD_ANALYSIS.find(f => 
    topBrightness >= f.range[0] && topBrightness <= f.range[1]
  ) || FOREHEAD_ANALYSIS[2];

  const eyesData = EYES_ANALYSIS.find(e => 
    midBrightness >= e.range[0] && midBrightness <= e.range[1]
  ) || EYES_ANALYSIS[2];

  const mouthData = MOUTH_CHIN_ANALYSIS.find(m => 
    bottomBrightness >= m.range[0] && bottomBrightness <= m.range[1]
  ) || MOUTH_CHIN_ANALYSIS[2];

  // 종합 점수 계산
  const totalScore = topBrightness + midBrightness + bottomBrightness;
  const overallData = OVERALL_FORTUNES.find(o => 
    totalScore >= o.scoreRange[0] && totalScore <= o.scoreRange[1]
  ) || OVERALL_FORTUNES[4];

  // 오행 분석
  const fiveElements = analyzeFiveElements(topBrightness, midBrightness, bottomBrightness);
  
  // 십이궁 분석
  const twelveHouses = analyzeTwelveHouses(topBrightness, midBrightness, bottomBrightness);

  // 행운 요소 계산
  const avgBrightness = totalScore / 3;
  const luckyColor = LUCKY_COLORS[Math.floor(avgBrightness / 17) % LUCKY_COLORS.length];
  const luckyNumber = Math.floor(topBrightness / 2.55) + Math.floor(midBrightness / 2.55);
  const luckyDirection = LUCKY_DIRECTIONS[Math.floor(bottomBrightness / 31.875) % LUCKY_DIRECTIONS.length];
  const luckyMonth = LUCKY_MONTHS[Math.floor(totalScore / 63.75) % LUCKY_MONTHS.length];

  // 추천 보충제 (4개 카테고리 조합)
  const supplements: string[] = [];
  const indices = [
    Math.floor(topBrightness / 51) % SUPPLEMENT_RECOMMENDATIONS.length,
    Math.floor(midBrightness / 51) % SUPPLEMENT_RECOMMENDATIONS.length,
    Math.floor(bottomBrightness / 51) % SUPPLEMENT_RECOMMENDATIONS.length
  ];
  
  indices.forEach((idx, i) => {
    const category = SUPPLEMENT_RECOMMENDATIONS[idx];
    const itemIdx = (topBrightness + midBrightness + bottomBrightness + i * 31) % category.length;
    supplements.push(category[itemIdx]);
  });

  // 강점/약점/기회/위협 분석
  const strengths = [
    foreheadData.personality.split('.')[0],
    eyesData.personality.split('.')[0],
    mouthData.personality.split('.')[0]
  ];

  const weaknesses = totalScore < 200 
    ? ["과도한 신중함으로 기회를 놓칠 수 있음", "자신감 부족", "소극적 태도"] 
    : totalScore > 600 
    ? ["과신으로 인한 방심 가능", "무리한 도전", "교만함 주의"] 
    : ["완벽주의 성향", "스트레스 관리 필요", "일과 휴식 밸런스"];

  const opportunities = [
    overallData.advice,
    foreheadData.career.split('.')[0],
    eyesData.love.split('.')[0]
  ];

  const threats = totalScore < 150 
    ? ["기회를 놓칠 수 있음", "소극적 태도로 인한 손실", "변화에 대한 두려움"] 
    : totalScore > 650 
    ? ["과욕으로 인한 실패 가능성", "교만함으로 인한 인간관계 악화"] 
    : ["경쟁 심화", "환경 급변", "예상치 못한 변수"];

  return {
    overall: `${overallData.level} - ${overallData.description}`,
    wealth: foreheadData.wealth,
    career: foreheadData.career,
    love: eyesData.love,
    health: mouthData.health,
    personality: `${foreheadData.personality} ${eyesData.personality}`.substring(0, 200) + "...",
    strengths,
    weaknesses,
    opportunities,
    threats,
    luckyColor,
    luckyNumber,
    luckyDirection,
    luckyMonth,
    recommendations: [...new Set([...foreheadData.recommendations, ...supplements])].slice(0, 5),
    detailedAnalysis: {
      forehead: `【${foreheadData.title}】\n\n${foreheadData.sanjeong}\n\n${foreheadData.fortune}\n\n${foreheadData.career}`,
      eyes: `【${eyesData.title}】\n\n${eyesData.sanjeong}\n\n${eyesData.fortune}\n\n${eyesData.socialLuck}`,
      nose: `【중앙부·준두(準頭)】\n\n코는 재물궁(財帛宮)이자 자존감의 상징입니다. 현재 당신의 코는 ${midBrightness > 150 ? "높고 반듯하여 재물운이 뛰어나며 자존감도 건강" : midBrightness > 100 ? "균형잡혀 있어 안정적인 재물운" : "조금 낮아 재물 관리에 신중함이 필요"}합니다.`,
      mouth: `【${mouthData.title}】\n\n${mouthData.sanjeong}\n\n${mouthData.fortune}\n\n식복(食福): ${mouthData.laterYears}`,
      chin: `【하관·지각(地閣)】\n\n턱은 말년운과 자손운을 나타냅니다. ${mouthData.laterYears}\n\n자손운: 당신의 자녀들은 효도하며 가문을 빛낼 것입니다. 손자 대에는 더욱 번창할 가능성이 큽니다.`
    },
    twelveHouses,
    fiveElements
  };
}
